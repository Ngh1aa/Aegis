import { mkdir } from 'node:fs/promises'
import { expect, test, type Page } from '@playwright/test'

async function review(page: Page, item: string, name: string) {
  await page.locator('summary').filter({ hasText: item }).click()
  const checkbox = page.getByRole('checkbox', { name })
  await checkbox.click()
  await expect(checkbox).toBeChecked()
}
async function reason(page: Page, content: string) {
  await page.getByRole('textbox', { name: 'Decision reason' }).fill(content)
}
const reviewDecision = (page: Page) => page.getByRole('button', { name: 'Review decision' })
const confirmation = (page: Page, title: string) => page.getByRole('dialog', { name: title, exact: true })
async function capture(page: Page, name: string) {
  const folder = process.env.AEGIS_CAPTURES
  if (!folder) return
  await mkdir(folder, { recursive: true })
  await page.screenshot({ path: folder + '/' + name + '.png' })
}

test('A: queue context, missing reason and evidence, cancel, confirmed disposition and audit backlink', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.goto('/#/')
  await page.getByRole('link', { name: /critical alerts/i }).click()
  await page.getByRole('searchbox', { name: 'Search transactions' }).fill('Northline')
  await page.getByRole('combobox', { name: 'Sort transactions' }).selectOption('risk')
  const queue = page.url()
  await page.getByRole('link', { name: 'TX-8421', exact: true }).click()
  await expect(page.getByRole('main')).toBeFocused()
  await page.getByRole('link', { name: 'Back to previous view' }).click()
  await expect(page).toHaveURL(queue)
  const selection = page.getByRole('link', { name: 'TX-8421', exact: true })
  await expect(selection).toBeFocused()
  await expect(page.getByRole('searchbox')).toHaveValue('Northline')
  await selection.click()
  await expect(page.getByText('Low confidence')).toBeVisible()
  await page.getByRole('combobox', { name: 'Decision', exact: true }).selectOption('Block payment')
  await expect(reviewDecision(page)).toBeDisabled()
  await expect(page.getByText(/at least 12 characters/)).toBeVisible()
  const basis = 'Authorization velocity corroborated by a repeated device fingerprint.'
  await reason(page, basis)
  await expect(reviewDecision(page)).toBeDisabled()
  await expect(page.getByText('Review all required evidence or escalate the case.')).toBeVisible()
  await review(page, 'Authorization record', 'Mark authorization record reviewed')
  await review(page, 'Device and session record', 'Mark device and session record reviewed')
  await page.getByRole('textbox', { name: 'Investigator note' }).fill('Device evidence checked before disposition.')
  await page.getByRole('button', { name: 'Save note' }).click()
  await expect(page.getByText('Device evidence checked before disposition.')).toBeVisible()
  await reviewDecision(page).click()
  const dialog = confirmation(page, 'Block payment')
  await expect(dialog).toContainText('USD 2,840.00')
  await expect(dialog).toContainText('TX-8421')
  await expect(dialog).toContainText('CS-2401')
  await capture(page, 'flow-a-confirmation')
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByRole('textbox', { name: 'Decision reason' })).toHaveValue(basis)
  await reviewDecision(page).click()
  await dialog.getByRole('button', { name: 'Block payment', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Decision recorded' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Payment status' })).toContainText('Declined')
  await capture(page, 'flow-a-result')
  await page.getByRole('link', { name: 'CS-2401', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'CS-2401', exact: true })).toBeVisible()
  await expect(page.getByText('Resolved', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Audit trail', exact: true }).click()
  const event = page.getByRole('row').filter({ hasText: 'Block payment' })
  await expect(event).toContainText(basis)
  await expect(event).toContainText('Maya Chen')
  await expect(event).toContainText('Declined')
  await event.getByRole('link', { name: 'TX-8421' }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Decision recorded' })).toBeVisible()
  await page.getByRole('link', { name: 'Analytics', exact: true }).click()
  await page.getByRole('link', { name: '9 Nov 3 cases resolved' }).click()
  await expect(page.getByRole('row').filter({ hasText: 'CS-2401' })).toContainText('Resolved')
})

