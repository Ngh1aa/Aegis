test('rule test, stale input, publish review and protected rule', async ({ page }) => {
  await page.goto('/#/rules/RULE-103')
  const threshold = page.getByRole('spinbutton')
  const run = page.getByRole('button', { name: 'Run test' })
  await threshold.fill('0')
  await run.click()
  await expect(page.getByRole('alert')).toContainText('whole number')
  await threshold.fill('100')
  await run.click()
  await expect(page.getByRole('heading', { name: 'No matching transactions' })).toBeVisible()
  await threshold.fill('82')
  await page.getByRole('checkbox', { name: 'Activate on publish' }).check()
  const publish = page.getByRole('button', { name: 'Review changes' })
  await expect(publish).toBeDisabled()
  await run.click()
  await publish.click()
  await confirmation(page, 'Publish changes').getByRole('button', { name: 'Publish changes' }).click()
  await expect(page.getByText('RULE-103 updated.')).toBeVisible()
  await page.getByRole('link', { name: 'Back to rules' }).click()
  await expect(page.getByRole('row').filter({ hasText: 'RULE-103' })).toContainText('Active')
  await page.getByRole('link', { name: 'RULE-104' }).click()
  await expect(page.getByText(/Permission denied/)).toBeVisible()
  await expect(publish).toBeDisabled()
})

