test('corrupt storage can be retried or restored explicitly', async ({ page }) => {
  await page.addInitScript(() => {
    if (!localStorage.getItem('aegis.workspace.v1')) localStorage.setItem('aegis.workspace.v1', '{')
  })
  await page.goto('/#/')
  await expect(page.getByRole('heading', { name: 'Workspace unavailable' })).toBeVisible()
  await page.getByRole('button', { name: 'Retry' }).click()
  await expect(page.getByRole('heading', { name: 'Workspace unavailable' })).toBeVisible()
  await page.getByRole('button', { name: 'Restore records' }).click()
  await confirmation(page, 'Restore records').getByRole('button', { name: 'Restore records' }).click()
  await expect(page.getByRole('heading', { name: 'Risk overview' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Risk overview' })).toBeVisible()
})

