test('stale review is rejected and keeps the reason available for retry', async ({ page, context }) => {
  await page.goto('/#/transactions/TX-8421')
  await page.getByRole('combobox', { name: 'Decision', exact: true }).selectOption('Escalate case')
  const basis = 'Refer the remaining risk signals to the Risk Manager.'
  await reason(page, basis)
  await reviewDecision(page).click()
  const dialog = confirmation(page, 'Escalate case')
  const secondTab = await context.newPage()
  await secondTab.goto('/#/cases/CS-2401')
  await secondTab.getByRole('combobox', { name: 'Assign case owner' }).selectOption('Jordan Ellis')
  await secondTab.getByRole('button', { name: 'Save assignment' }).click()
  await expect(secondTab.getByRole('status')).toContainText('assigned to Jordan Ellis')
  await secondTab.close()
  await dialog.getByRole('button', { name: 'Escalate case', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Records changed in another tab')
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByRole('textbox', { name: 'Decision reason' })).toHaveValue(basis)
  await reviewDecision(page).click()
  await dialog.getByRole('button', { name: 'Escalate case', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Escalated for review' })).toBeVisible()
})
